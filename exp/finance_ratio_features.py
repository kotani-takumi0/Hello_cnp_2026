"""H21: 木が作れない財務比（E1 財務・規模エキスパート専用）。

動機:
  E1 の32列は生の金額19本＋規模4本＋欠損フラグ6本＋H1利益率3本で、導出特徴は
  H1 の3本しかない。その3本が E1 の単体AP上位3位を独占し、gain も1列あたり
  7.7%（生の金額列の約3倍）を取っている。LightGBM は列の除算を再構築できない
  ので、比は足した分だけ効く余地が残っている。

過去の却下との違い:
  H2(財務健全性) / H3(1人あたり) / H7(CF比率) は E0(94列, テキストスコアが
  gain単独首位) の上で検証して全滅した。原因は概念ではなく重複で、既存E1列との
  最大|Spearman| は H7 営業CFマージン 0.993 / H3 各列 0.77〜0.85 だった。
  ここでは **単体APが正例率0.241を明確に上回り、既存E1列との|r|<0.5、かつ
  候補どうしでも重複しない** 4本だけを採る。
  - ROA は AP最良(0.449)だが営業利益率と r=0.703 なので不採用
    （入れた5本版は10seedで4本版に劣ることを確認済み）
  - 自己資本比率 は |r|=0.498 で基準内だが、純資産_総資産比 と r=0.992
    （分子の自己資本と純資産が r=0.999）なので片方だけ採る

診断値（train 742行, 正例率 0.2412）:
  列                    単体AUC  単体AP  AP倍率  既存E1との最大|r|
  ソフト投資比率_売上      0.724   0.408   1.69   0.417
  流動比率                0.629   0.396   1.64   0.450
  純資産_総資産比          0.631   0.397   1.65   0.481
  投資CF_売上比           0.649   0.340   1.41   0.286

行単位の決定的変換のみ＝リーク無し。
"""
import numpy as np

# E1 にだけ足す。E0(アンカー94列)には入れない（expert_groups.e0_anchor_cols が除外）。
FINANCE_RATIO_COLS = (
    "ソフト投資比率_売上",
    "流動比率",
    "純資産_総資産比",
    "投資CF_売上比",
)


def _safe_div(a, b):
    """ゼロ除算・無限大を欠損に落とす。LightGBM は欠損を分岐で扱える。"""
    return (a / b).replace([np.inf, -np.inf], np.nan)


def add_finance_ratios(df, X):
    """(生の train/test, 特徴量行列) -> 比4本を足した特徴量行列。

    `add_h1` / `add_org_manual_features` と同じ (df, X) -> X の規約。
    """
    X = X.copy()
    X["ソフト投資比率_売上"] = _safe_div(
        df["無形固定資産変動(ソフトウェア関連)"], df["売上"])
    X["流動比率"] = _safe_div(df["流動資産"], df["負債"])
    X["純資産_総資産比"] = _safe_div(df["純資産"], df["総資産"])
    X["投資CF_売上比"] = _safe_div(df["投資CF"], df["売上"])
    return X
